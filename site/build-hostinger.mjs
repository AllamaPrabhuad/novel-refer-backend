// Packages the site for Hostinger (or any Apache/LiteSpeed + PHP host).
// Usage: npm run build:hostinger  →  dist/novel-tissues-hostinger.zip
// Upload the zip to public_html in hPanel's File Manager and extract it there.
import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(here, "../public/b2b");
const DIST = path.resolve(here, "../dist");
const OUT = path.join(DIST, "hostinger");
const ZIP = path.join(DIST, "novel-tissues-hostinger.zip");

const configSrc = fs.readFileSync(path.join(SRC, "config.js"), "utf8");
const { CONTACT, SITE } = new Function(configSrc + "; return { CONTACT, SITE };")();
const host = new URL(SITE.url).host;
const bare = host.replace(/^www\./, "");

fs.rmSync(OUT, { recursive: true, force: true });
fs.rmSync(ZIP, { force: true });
fs.cpSync(SRC, OUT, { recursive: true });

// Forms post to the PHP handler instead of the Node server.
fs.writeFileSync(path.join(OUT, "config.js"),
  configSrc.replace(/endpoint:\s*"[^"]*"/, 'endpoint: "/api/enquiry.php"'));

fs.mkdirSync(path.join(OUT, "api"), { recursive: true });
fs.writeFileSync(path.join(OUT, "api/enquiry.php"),
  fs.readFileSync(path.join(here, "hostinger/enquiry.php"), "utf8").replace("__LEAD_EMAIL__", CONTACT.email));

const preferWww = host.startsWith("www.");
fs.writeFileSync(path.join(OUT, ".htaccess"), `# Novel Tissues — Hostinger settings (generated by npm run build:hostinger)
Options -Indexes
DirectoryIndex index.html index.php

RewriteEngine On
# Always use HTTPS
RewriteCond %{HTTPS} !=on
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
# One main address (${host}) so Google sees a single version of every page
${preferWww
    ? `RewriteCond %{HTTP_HOST} ^${bare.replace(/\./g, "\\.")}$ [NC]\nRewriteRule ^ https://${host}%{REQUEST_URI} [L,R=301]`
    : `RewriteCond %{HTTP_HOST} ^www\\.${bare.replace(/\./g, "\\.")}$ [NC]\nRewriteRule ^ https://${bare}%{REQUEST_URI} [L,R=301]`}

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/html "access plus 0 seconds"
  ExpiresByType text/css "access plus 7 days"
  ExpiresByType application/javascript "access plus 7 days"
  ExpiresByType image/png "access plus 30 days"
  ExpiresByType application/pdf "access plus 7 days"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml application/xml text/xml text/plain
</IfModule>
`);

execFileSync("zip", ["-qr", ZIP, "."], { cwd: OUT });
console.log(`wrote ${path.relative(process.cwd(), ZIP)} (${(fs.statSync(ZIP).size / 1024 / 1024).toFixed(1)} MB)`);
console.log(`leads email: ${CONTACT.email} · main address: https://${host}`);
